from datetime import datetime, timezone

from fastapi import APIRouter, Depends, HTTPException, Query

from app.core.audit import record_event
from app.core.config import settings
from app.core.database import check_database, get_db
from app.core.security import get_password_hash, require_roles
from app.core.metrics import snapshot

router = APIRouter()


@router.get("/metrics")
async def get_metrics(user=Depends(require_roles("admin")), db=Depends(get_db)):
    tenants = await db.organizations.count_documents({})
    users = await db.users.count_documents({})
    tasks = await db.tasks.count_documents({})
    api_metrics = snapshot()
    database_connected = await check_database()
    return {
        "status": "healthy" if database_connected else "degraded",
        "metrics": {
            "active_tenants": tenants,
            "active_users": users,
            "tasks": tasks,
            "api_requests": api_metrics["requests"],
            "failed_requests": api_metrics["failed_requests"],
            "backend": "HEALTHY",
            "database": "CONNECTED" if database_connected else "UNAVAILABLE",
            "latency_ms": api_metrics["average_latency_ms"],
            "metrics_scope": api_metrics["scope"],
            "simulation_limit": settings.MAX_SIMULATION_ITEMS,
        },
    }


@router.get("/tenants")
async def tenant_metrics(user=Depends(require_roles("admin")), db=Depends(get_db)):
    tenants = []
    async for tenant in db.organizations.find({}, {"name": 1}):
        tenant_id = str(tenant["_id"])
        tenants.append({
            "tenant_id": tenant_id,
            "name": tenant["name"],
            "users": await db.users.count_documents({"tenant_id": tenant_id}),
            "tasks": await db.tasks.count_documents({"tenant_id": tenant_id}),
        })
    return {"data": tenants}


@router.post("/simulate")
async def simulate(
    count: int = Query(10, ge=1, le=100),
    user=Depends(require_roles("admin")),
    db=Depends(get_db),
):
    count = min(count, settings.MAX_SIMULATION_ITEMS)
    now = datetime.now(timezone.utc)
    org = await db.organizations.insert_one({
        "name": f"Demo Cloud Corp {now.strftime('%Y%m%d%H%M%S')}",
        "created_at": now,
        "simulation": True,
    })
    tenant_id = str(org.inserted_id)
    demo_user = {
        "email": f"demo-{tenant_id}@cloud.local",
        "password_hash": get_password_hash("DemoOnly123!"),
        "full_name": "Cloud Demo User",
        "tenant_id": tenant_id,
        "role": "admin",
        "created_at": now,
        "simulation": True,
    }
    created_user = await db.users.insert_one(demo_user)
    task_ids = []
    for index in range(count):
        result = await db.tasks.insert_one({
            "tenant_id": tenant_id,
            "created_by": str(created_user.inserted_id),
            "assigned_to": str(created_user.inserted_id),
            "title": f"Demo task {index + 1}",
            "description": "Generated by the bounded Cloud Control Center simulation.",
            "status": "pending",
            "priority": "medium",
            "created_at": now,
            "updated_at": now,
            "simulation": True,
        })
        task_ids.append(str(result.inserted_id))
    await record_event(db, tenant_id=user["tenant_id"], user_id=user["user_id"],
                       action="CLOUD_SIMULATION", resource="simulation",
                       details={"created_tenant_id": tenant_id, "task_count": count})
    return {"message": "Simulation executed", "tenant_id": tenant_id, "task_count": len(task_ids)}


@router.post("/failure-test")
async def failure_test(
    mode: str = Query(..., pattern="^(database|authentication|tenant)$"),
    user=Depends(require_roles("admin")),
    db=Depends(get_db),
):
    if mode == "database":
        connected = await check_database()
        return {"mode": mode, "status": "connected" if connected else "unavailable", "simulated": True}
    if mode == "authentication":
        raise HTTPException(status_code=401, detail="Controlled authentication failure simulation")
    await record_event(db, tenant_id=user["tenant_id"], user_id=user["user_id"],
                       action="ACCESS_DENIED", resource="tenant", status="failure")
    raise HTTPException(status_code=403, detail="Controlled tenant isolation failure simulation")
